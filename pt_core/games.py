# -*- coding: utf-8 -*-
"""本地游戏检测。

识别三类目标:
  bepinex    — BepInEx + XUnity.AutoTranslator (目录特征: BepInEx/)
  standalone — XUAT 独立版/ReiPatcher (目录特征: AutoTranslator/Config.ini)
  unity      — 裸 Unity 游戏 (UnityPlayer.dll), 尚未安装 XUAT
翻译目录: BepInEx 版在 BepInEx/Translation/, 独立版在 AutoTranslator/Translation/。
"""
import os
import re
import shutil
import time

PRUNE_DIRS = {
    'windows', 'program files', 'program files (x86)', 'programdata', 'users',
    'appdata', '$recycle.bin', 'system volume information', 'recovery',
    'perflogs', 'node_modules', '.git', '.svn', '__pycache__', 'onedrive',
    'onedrivetemp', 'intel', 'drivers', 'dell', 'swsetup', 'esupport',
}

IGNORED_EXE = ('crashhandler', 'uninstall', 'setup')

# XUAT 5.6.x 独立版首次运行会生成此配置; 这里预置同样的模板以便打补丁后立即生效
