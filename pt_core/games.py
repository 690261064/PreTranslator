class Game:
    def __init__(self, root, kind):
        self.root = root
        self.kind = kind          # bepinex / standalone / unity
        self.name = os.path.basename(root.rstrip('\\/')) or root
        self.exe = ''
        self.il2cpp = False
        self.managed_dir = ''
        if kind == 'bepinex':
            self.bepinex = os.path.join(root, 'BepInEx')
            self.translation_dir = os.path.join(self.bepinex, 'Translation')
            self.config_ini = os.path.join(self.bepinex, 'config', 'AutoTranslatorConfig.ini')
            self.xuat_dll = ''
        elif kind == 'standalone':
            self.bepinex = ''
            self.translation_dir = os.path.join(root, 'AutoTranslator', 'Translation')
            self.config_ini = os.path.join(root, 'AutoTranslator', 'Config.ini')
            self.xuat_dll = ''
        else:
            self.bepinex = ''
            self.translation_dir = os.path.join(root, 'AutoTranslator', 'Translation')
            self.config_ini = ''
            self.xuat_dll = ''
        self._find_exe()
        self._find_runtime()

    def _find_exe(self):
        try:
            for fn in os.listdir(self.root):
                if fn.lower().endswith('.exe'):
                    low = fn.lower()
                    if any(x in low for x in IGNORED_EXE):
                        continue
                    if not self.exe:
                        self.exe = os.path.join(self.root, fn)
        except OSError:
            pass

    def _find_runtime(self):
        """定位 Managed 目录并判断 Mono/IL2CPP。"""
        try:
            for fn in os.listdir(self.root):
                if fn.lower().endswith('_data'):
                    data_dir = os.path.join(self.root, fn)
                    managed = os.path.join(data_dir, 'Managed')
                    if os.path.isdir(managed):
                        self.managed_dir = managed
                    if (os.path.isfile(os.path.join(data_dir, 'il2cpp_data'))
                            or os.path.isfile(os.path.join(self.root, 'GameAssembly.dll'))):
                        self.il2cpp = True
        except OSError:
            pass

    def target_dir(self, target_lang):
        return os.path.join(self.translation_dir, target_lang)

    @property
    def has_xuat(self):
        if self.kind == 'bepinex':
            return bool(self.xuat_dll or self.config_ini)
        if self.kind == 'standalone':
            return True
        return False

    @property
    def kind_label(self):
        if self.kind == 'bepinex':
            return 'BepInEx'
        if self.kind == 'standalone':
            return '独立版'
        return 'IL2CPP' if self.il2cpp else '未装XUAT'

    def read_ini(self):
        vals = {}
        if not self.config_ini or not os.path.isfile(self.config_ini):
            return vals
        try:
            with open(self.config_ini, encoding='utf-8-sig', errors='replace') as f:
                for line in f:
                    line = line.strip()
                    if not line or line.startswith((';', '#', '[')):
                        continue
                    if '=' in line:
                        k, v = line.split('=', 1)
                        vals[k.strip()] = v.strip()
        except OSError:
            pass
        return vals

    def ensure_config(self, log_fn=print):
        """XUAT 已装但配置尚未生成时预生成 (独立版/BepInEx 版通用)。
        BepInEx 版常见于 IL2CPP: 组件解压后、游戏首跑前。"""
        if self.kind == 'standalone':
            if self.config_ini:
                return True
            at_dir = os.path.join(self.root, 'AutoTranslator')
            try:
                os.makedirs(os.path.join(at_dir, 'Translation', 'zh-CN', 'Text'),
                            exist_ok=True)
                with open(os.path.join(at_dir, 'Config.ini'), 'w',
                          encoding='utf-8-sig') as f:
                    f.write(STANDALONE_CONFIG_TEMPLATE)
                self.config_ini = os.path.join(at_dir, 'Config.ini')
                log_fn('已预生成独立版配置: %s' % self.config_ini, 'ok')
                return True
            except OSError as e:
                log_fn('配置预生成失败: %s' % e, 'err')
                return False
        if self.kind == 'bepinex' and not self.config_ini and self.xuat_dll:
            try:
                cfg_dir = os.path.join(self.bepinex, 'config')
                os.makedirs(cfg_dir, exist_ok=True)
                p = os.path.join(cfg_dir, 'AutoTranslatorConfig.ini')
                with open(p, 'w', encoding='utf-8-sig') as f:
                    f.write(STANDALONE_CONFIG_TEMPLATE)
                self.config_ini = p
                log_fn('已预生成 BepInEx 版配置: %s' % p, 'ok')
                return True
            except OSError as e:
                log_fn('配置预生成失败: %s' % e, 'err')
                return False
        return True

    def fix_config(self, target_lang='zh-CN', from_lang='ja', override_font=None,
                   log_fn=print, max_chars=None):
        """修正 XUAT 配置: 目标/源语言、热重载、中文字体覆盖 (解决方框乱码)。"""
        if self.kind == 'standalone':
            self.ensure_config(log_fn=log_fn)
        ini = self.config_ini
        if not ini or not os.path.isfile(ini):
            return False
        try:
            with open(ini, encoding='utf-8-sig') as f:
                lines = f.read().splitlines()
        except OSError:
            return False
        section = ''
        changed = []
        out = []
        for line in lines:
            stripped = line.strip()
            if stripped.startswith('['):
                section = stripped.strip('[]').strip().lower()
            key = stripped.split('=', 1)[0].strip().lower() if '=' in stripped else None
            val = stripped.split('=', 1)[1].strip() if '=' in stripped else ''
            new = line
            if key == 'language' and section == 'general':
                if val.lower() != target_lang.lower():
                    new = 'Language=' + target_lang
                    changed.append('Language=%s' % target_lang)
            elif key == 'fromlanguage' and section == 'general':
                if from_lang and val.lower() != from_lang.lower():
                    new = 'FromLanguage=' + from_lang
                    changed.append('FromLanguage=%s' % from_lang)
            elif key == 'reloadtranslationsonfilechange':
                if val.lower() != 'true':
                    new = 'ReloadTranslationsOnFileChange=True'
                    changed.append('ReloadTranslationsOnFileChange=True')
            elif override_font and key == 'overridefont' and not val:
                new = 'OverrideFont=' + override_font
                changed.append('OverrideFont=' + override_font)
            elif override_font and key == 'overridefonttextmeshpro' and not val:
                new = 'OverrideFontTextMeshPro=' + override_font
                changed.append('OverrideFontTextMeshPro=' + override_font)
            elif max_chars and key == 'maxcharacterspertranslation' and section == 'behaviour':
                try:
                    cur = int(val or '200')
                except ValueError:
                    cur = 200
                if cur < max_chars:
                    new = 'MaxCharactersPerTranslation=%d' % max_chars
                    changed.append('MaxCharactersPerTranslation=%d' % max_chars)
            out.append(new)
        if changed:
            try:
                with open(ini, 'w', encoding='utf-8-sig') as f:
                    f.write('\n'.join(out) + '\n')
                log_fn('已修正 XUAT 配置 (%s): %s' % (ini, ', '.join(changed)), 'ok')
                return True
            except OSError as e:
                log_fn('配置修正失败: %s' % e, 'err')
                return False
        return False

    def summary(self, target_lang):
        tdir = self.target_dir(target_lang)
        tgt = '已存在缓存' if os.path.isdir(tdir) else '无缓存'
        return '%s | %s | %s' % (self.name, self.kind_label, tgt)


def read_xuat_max_chars(game, default=200):
    """读游戏 XUAT 配置里的 MaxCharactersPerTranslation (超过该长度的文本 XUAT 不翻译)。"""
    ini = game.config_ini
    if not ini or not os.path.isfile(ini):
        return default
    section = ''
    try:
        with open(ini, encoding='utf-8-sig', errors='replace') as f:
            for line in f:
                s = line.strip()
                if s.startswith('['):
                    section = s.strip('[]').strip().lower()
                elif '=' in s and section == 'behaviour':
                    k, v = s.split('=', 1)
                    if k.strip().lower() == 'maxcharacterspertranslation':
                        try:
                            return int(v.strip() or default)
                        except ValueError:
                            return default
    except OSError:
        pass
    return default


def detect_at(root):
    """检测目录是哪类游戏; 都不是返回 None。"""
    if not root or not os.path.isdir(root):
        return None
    if os.path.isdir(os.path.join(root, 'BepInEx')):
        g = Game(root, 'bepinex')
        plugins = os.path.join(g.bepinex, 'plugins')
        if os.path.isdir(plugins):
            for dp, dns, fns in os.walk(plugins):
                if dp[len(plugins):].count(os.sep) > 3:
                    dns[:] = []
                    continue
                for fn in fns:
                    low = fn.lower()
                    if low.startswith('xunity.autotranslator') and low.endswith('.dll'):
                        g.xuat_dll = os.path.join(dp, fn)
                        break
                if g.xuat_dll:
                    break
        return g
    if os.path.isfile(os.path.join(root, 'AutoTranslator', 'Config.ini')):
        return Game(root, 'standalone')
    # 独立版已打补丁但尚未生成配置: Managed 里有 XUAT 核心即可认定
    try:
        for fn in os.listdir(root):
            if fn.lower().endswith('_data') and os.path.isdir(os.path.join(root, fn)):
                core = os.path.join(root, fn, 'Managed',
                                    'XUnity.AutoTranslator.Plugin.Core.dll')
                if os.path.isfile(core):
                    return Game(root, 'standalone')
    except OSError:
        pass
    # 裸 Unity: UnityPlayer.dll 或 *_Data 目录
    has_data = False
    try:
        for fn in os.listdir(root):
            low = fn.lower()
            if low == 'unityplayer.dll' or low == 'gameassembly.dll':
                return Game(root, 'unity')
            if low.endswith('_data') and os.path.isdir(os.path.join(root, fn)):
                has_data = True
    except OSError:
        return None
    if has_data:
        return Game(root, 'unity')
    return None


def managed_dlls(game):
    """返回游戏 Managed 目录下可提取字符串的关键 DLL。"""
    out = []
    md = game.managed_dir
    if not md or not os.path.isdir(md):
        return out
    for fn in sorted(os.listdir(md)):
        low = fn.lower()
        if low.endswith('.dll') and (low.startswith('assembly-csharp') or low == 'unityplayer.dll'):
            out.append(os.path.join(md, fn))
    if not out:
        for fn in sorted(os.listdir(md)):
            if fn.lower().endswith('.dll') and 'assembly' in fn.lower():
                out.append(os.path.join(md, fn))
    return out


def il2cpp_metadata_file(game):
    """IL2CPP 游戏的 global-metadata.dat 路径 (含全部字符串字面量)。"""
    if not game.il2cpp:
        return None
    try:
        for fn in os.listdir(game.root):
            if fn.lower().endswith('_data') and os.path.isdir(os.path.join(game.root, fn)):
                p = os.path.join(game.root, fn, 'il2cpp_data', 'Metadata',
                                 'global-metadata.dat')
                if os.path.isfile(p):
                    return p
    except OSError:
        pass
    return None


def pe_arch(path):
    """读取 PE 头判断 x64/x86。"""
    import struct
    try:
        with open(path, 'rb') as f:
            d = f.read(4096)
        pe = struct.unpack_from('<I', d, 0x3C)[0]
        m = struct.unpack_from('<H', d, pe + 4)[0]
        return 'x64' if m == 0x8664 else 'x86' if m == 0x14C else None
    except OSError:
        return None


# ---------------- IL2CPP 自动安装 (BepInEx 6 + XUAT IL2CPP) ----------------

BEPINEX6_URL = ('https://github.com/BepInEx/BepInEx/releases/download/'
                'v6.0.0-pre.2/BepInEx-Unity.IL2CPP-win-{arch}-6.0.0-pre.2.zip')
XUAT_IL2CPP_URL = ('https://github.com/bbepis/XUnity.AutoTranslator/releases/'
                   'download/v5.6.3.1/XUnity.AutoTranslator-BepInEx-IL2CPP-5.6.3.1.zip')
XUAT_RR_IL2CPP_URL = ('https://github.com/bbepis/XUnity.AutoTranslator/releases/'
                      'download/v5.6.3.1/XUnity.ResourceRedirector-BepInEx-IL2CPP-2.1.0.zip')


def download(url, dst, log_fn=print, timeout=300, store_dir=None):
    """下载文件; github 直连失败自动走 gh-proxy 镜像; store_dir 命中缓存则直接复用。"""
    import urllib.request
    if store_dir:
        os.makedirs(store_dir, exist_ok=True)
        cached = os.path.join(store_dir, os.path.basename(url.split('?')[0]))
        if os.path.isfile(cached) and os.path.getsize(cached) > 0:
            log_fn('使用已缓存下载: %s' % os.path.basename(cached))
            shutil.copy2(cached, dst)
            return True
    urls = [url, 'https://gh-proxy.com/' + url]
    last = None
    for u in urls:
        try:
            log_fn('下载: %s' % u)
            req = urllib.request.Request(u, headers={'User-Agent': 'PreTranslator/1.0'})
            with urllib.request.urlopen(req, timeout=timeout) as r, open(dst, 'wb') as f:
                while True:
                    chunk = r.read(256 * 1024)
                    if not chunk:
                        break
                    f.write(chunk)
            if os.path.getsize(dst) > 0:
                if store_dir:
                    try:
                        shutil.copy2(dst, cached)
                    except OSError:
                        pass
                return True
        except Exception as e:
            last = e
            log_fn('下载失败: %s' % str(e)[:120], 'warn')
    log_fn('所有下载源均失败: %s' % last, 'err')
    return False


def install_il2cpp(game, cfg, log_fn=print):
    """为 IL2CPP 游戏安装 BepInEx 6 (IL2CPP) + XUnity.AutoTranslator IL2CPP 版。
    返回 True 表示文件已就位 (首次进游戏生成 interop 后, 第二次启动 XUAT 生效)。"""
    import tempfile
    import zipfile
    from .config import TOOL_DIR
    ga = None
    for fn in os.listdir(game.root):
        if fn.lower() == 'gameassembly.dll':
            ga = os.path.join(game.root, fn)
            break
    if not ga:
        log_fn('未找到 GameAssembly.dll, 不是 IL2CPP 游戏', 'err')
        return False
    arch = pe_arch(ga) or 'x64'
    jobs = [
        ('BepInEx6-IL2CPP-' + arch, BEPINEX6_URL.format(arch=arch)),
        ('XUAT-IL2CPP', XUAT_IL2CPP_URL),
        ('ResourceRedirector-IL2CPP', XUAT_RR_IL2CPP_URL),
    ]
    store = os.path.join(TOOL_DIR, 'cache', 'downloads')
    tmpd = tempfile.mkdtemp(prefix='pt_il2cpp_')
    ok_all = True
    for name, url in jobs:
        dst = os.path.join(tmpd, name + '.zip')
        if not download(url, dst, log_fn=log_fn, store_dir=store):
            ok_all = False
            continue
        try:
            with zipfile.ZipFile(dst) as zf:
                zf.extractall(game.root)
            log_fn('已解压 %s -> 游戏目录' % name, 'ok')
        except zipfile.BadZipFile as e:
            log_fn('解压失败 %s: %s' % (name, e), 'err')
            ok_all = False
    return ok_all


def unity_asset_files(game, max_file_mb=120):
    """返回可能含文本的 Unity 资源文件 (排除 resS/音频视频等大二进制流)。"""
    out = []
    try:
        for fn in os.listdir(game.root):
            if fn.lower().endswith('_data') and os.path.isdir(os.path.join(game.root, fn)):
                data_dir = os.path.join(game.root, fn)
                break
        else:
            return out
    except OSError:
        return out
    skip_ext = ('.ress', '.resource.bak', '.mp4', '.webm', '.bytes.bak')
    ok_ext = ('.assets', '.resource', '.asset', '.bytes', '.dat', '.txt', '.json', '.csv')
    for dirpath, dns, fns in os.walk(data_dir):
        dns[:] = [d for d in dns if d.lower() not in ('streamingassets',) or True]
        for fn in fns:
            low = fn.lower()
            full = os.path.join(dirpath, fn)
            if low.endswith(skip_ext) or low.endswith('.ress'):
                continue
            if 'streamingassets' in dirpath.lower() and not low.endswith(ok_ext):
                continue
            if not (low.endswith(ok_ext) or low.startswith('level')
                    or low.startswith('globalgamemanagers') or low.startswith('sharedassets')
                    or low.startswith('resources')):
                continue
            try:
                if os.path.getsize(full) > max_file_mb * 1024 * 1024:
                    continue
            except OSError:
                continue
            out.append(full)
    return out


def fixed_drives():
    try:
        drives = os.listdrives()
    except Exception:
        drives = []
    out = []
    for d in drives:
        p = d if d.endswith('\\') else d + '\\'
        if os.path.isdir(p):
            out.append(p)
    if not out:
        for L in 'CDEFGH':
            p = L + ':\\'
            if os.path.isdir(p):
                out.append(p)
    return out


def steam_libraries():
    """从 Steam 的 libraryfolders.vdf 解析所有 Steam 库目录。"""
    libs = []
    vdf_cands = [
        r'C:\Program Files (x86)\Steam\steamapps\libraryfolders.vdf',
        r'C:\Program Files\Steam\steamapps\libraryfolders.vdf',
    ]
    for vdf in vdf_cands:
        if os.path.isfile(vdf):
            try:
                txt = open(vdf, encoding='utf-8', errors='replace').read()
                for m in re.finditer(r'"path"\s+"([^"]+)"', txt):
                    p = m.group(1).replace('\\\\', '\\')
                    if p not in libs:
                        libs.append(p)
            except OSError:
                pass
            break
    return libs


def default_roots(cfg_roots):
    roots = list(cfg_roots or [])
    if not roots:
        roots = fixed_drives()
    for lib in steam_libraries():
        common = os.path.join(lib, 'steamapps', 'common')
        if os.path.isdir(common) and common not in roots:
            roots.append(common)
    return roots


def cache_name_for(root):
    """游戏根目录 -> 缓存目录名 (游戏名-hash)。

    规范化路径 (分隔符/大小写) 后再哈希: 同一目录不同写法不会分裂缓存。
    cache_dir_for 与缓存维护界面共用, 两边算出的名字必须一致。
    """
    import hashlib
    name = os.path.basename(root.rstrip('\\/')) or root
    safe = re.sub(r'[^\w.-]+', '_', name)[:40] or 'game'
    key = os.path.normcase(os.path.normpath(root))
    h = hashlib.sha1(key.encode('utf-8')).hexdigest()[:10]
    return '%s-%s' % (safe, h)


def cache_dir_for(game, tool_dir):
    """每个游戏的翻译断点缓存目录 (工具目录/cache/游戏名-hash)。"""
    return os.path.join(tool_dir, 'cache', cache_name_for(game.root))


def scan(roots, log_fn=print, max_depth=5, time_budget=240, max_dirs=400000):
    """BFS 扫描各根目录: 找 BepInEx/AutoTranslator 目录与 UnityPlayer.dll。"""
    t0 = time.time()
    found = {}
    scanned = [0]

    def add(root):
        g = detect_at(root)
        if g:
            found[g.root] = g
            log_fn('发现游戏: %s [%s] (%s)' % (g.name, g.kind_label, g.root))

    def visit(root, depth):
        if depth > max_depth or time.time() - t0 > time_budget:
            return
        try:
            entries = list(os.scandir(root))
        except OSError:
            return
        for e in entries:
            nm = e.name.lower()
            if e.is_dir(follow_symlinks=False):
                if nm in PRUNE_DIRS or nm.startswith(('$', '.')):
                    continue
                full = e.path
                if nm == 'bepinex':
                    add(os.path.dirname(full))
                    continue
                if nm == 'autotranslator':
                    if os.path.isfile(os.path.join(full, 'Config.ini')):
                        add(os.path.dirname(full))
                    continue
                scanned[0] += 1
                if scanned[0] > max_dirs:
                    log_fn('已达目录扫描上限, 提前结束')
                    return
                visit(full, depth + 1)
            else:
                if nm == 'unityplayer.dll':
                    add(root)
                    return  # 该目录已确认为游戏根

    for r in roots:
        if not os.path.isdir(r):
            continue
        visit(r, 1)
        log_fn('扫描完成: %s (累计 %d 目录, %.0fs)' % (r, scanned[0], time.time() - t0))
        if time.time() - t0 > time_budget:
            log_fn('已达扫描时限, 提前结束 (可用"添加扫描目录"缩小范围)')
            break
    return list(found.values())
